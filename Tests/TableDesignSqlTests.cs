using MosaicDB.Core;
using MosaicDB.Core.Models;
using Xunit;

namespace MosaicDB.Tests;

public sealed class TableDesignSqlTests
{
    private static TableDesign Sample() => new("t", "t",
        [
            new DesignColumn("id", "id", "int", NotNull: true, KeyOrder: 1, AutoIncrement: true),
            new DesignColumn("name", "name", "varchar", 50, Default: "'x'"),
            new DesignColumn("price", "price", "decimal", 10, 2),
        ],
        [new DesignIndex("ix_name", "ix_name", ["name"])],
        [], [], new TableDesignOptions("InnoDB"), null, "PRIMARY");

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void UnchangedDesignProducesNoStatements(bool mysql) =>
        Assert.Empty(TableDesignSql.Build(mysql, "public", Sample(), Sample()));

    [Fact]
    public void MySqlRenameKeepsIndexAndUsesChangeColumn()
    {
        var original = Sample();
        var target = original with
        {
            Columns = original.Columns.Select(c => c.Name == "name" ? c with { Name = "title", Length = 80 } : c).ToArray(),
            Indexes = [new DesignIndex("ix_name", "ix_name", ["title"])],
        };
        var sql = Assert.Single(TableDesignSql.Build(true, "db", original, target));
        Assert.Contains("CHANGE COLUMN `name` `title` varchar(80) NULL DEFAULT 'x' AFTER `id`", sql);
        Assert.DoesNotContain("INDEX", sql); // l'indice segue la colonna rinominata: niente DROP/ADD
    }

    [Fact]
    public void PostgresChangesAreSplitIntoAlterStatements()
    {
        var original = Sample();
        var target = original with
        {
            Columns = original.Columns.Select(c => c.Name == "price" ? c with { NotNull = true, Decimals = 3 } : c)
                .Append(new DesignColumn(null, "note", "text", Comment: "nota")).ToArray(),
        };
        var sql = TableDesignSql.Build(false, "public", original, target);
        Assert.Contains("ALTER TABLE \"public\".\"t\"\n  ALTER COLUMN \"price\" TYPE decimal(10,3) USING \"price\"::decimal(10,3),\n  ALTER COLUMN \"price\" SET NOT NULL", sql);
        Assert.Contains("ALTER TABLE \"public\".\"t\" ADD COLUMN \"note\" text", sql);
        Assert.Contains("COMMENT ON COLUMN \"public\".\"t\".\"note\" IS 'nota'", sql);
    }

    [Fact]
    public void NewTableBuildsCreateWithPrimaryKey()
    {
        var design = Sample() with { OriginalName = null, Columns = Sample().Columns.Select(c => c with { OriginalName = null }).ToArray(), Indexes = [] };
        var mysql = Assert.Single(TableDesignSql.Build(true, "db", null, design));
        Assert.StartsWith("CREATE TABLE `t` (", mysql);
        Assert.Contains("`id` int NOT NULL AUTO_INCREMENT", mysql);
        Assert.Contains("PRIMARY KEY (`id`)", mysql);
        Assert.Contains("ENGINE = InnoDB", mysql);
        var postgres = TableDesignSql.Build(false, "public", null, design)[0];
        Assert.Contains("\"id\" int GENERATED BY DEFAULT AS IDENTITY NOT NULL", postgres);
    }
}
