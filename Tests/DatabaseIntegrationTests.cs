using System.Data.Common;
using Navifox.Core;
using Navifox.Core.Models;
using Navifox.Dialects;
using Xunit;
using Xunit.Abstractions;

namespace Navifox.Tests;

/// <summary>
/// Test sui server veri (MySQL e PostgreSQL in localhost, presi dalle connessioni salvate di Navifox).
/// Si attivano con la variabile d'ambiente NAVIFOX_IT=1; ognuno lavora su un database temporaneo «navifox_selftest_…» che poi elimina.
/// </summary>
public sealed class DatabaseIntegrationTests(ITestOutputHelper output)
{
    private static bool Enabled => Environment.GetEnvironmentVariable("NAVIFOX_IT") == "1";

    public static IEnumerable<object[]> Kinds() => [[DatabaseKind.MySql], [DatabaseKind.PostgreSql]];

    private static async Task<(IDialectProvider Provider, ConnectionProfile Profile)?> ServerAsync(DatabaseKind kind)
    {
        var profiles = await new ConnectionProfileStore().LoadAsync();
        var profile = profiles.FirstOrDefault(p => p.Kind == kind && p.Host is "localhost" or "127.0.0.1");
        if (profile is null) return null;
        IDialectProvider provider = kind == DatabaseKind.MySql ? new MySqlDialectProvider() : new PostgreSqlDialectProvider();
        return (provider, profile);
    }

    /// <summary>Crea un database temporaneo, esegue il test con una connessione aperta su di esso e lo elimina.</summary>
    private async Task WithTemporaryDatabaseAsync(DatabaseKind kind, Func<IDialectProvider, DbConnection, string, Task> test)
    {
        if (!Enabled) { output.WriteLine("NAVIFOX_IT non impostata: test saltato."); return; }
        if (await ServerAsync(kind) is not var (provider, profile))
        {
            output.WriteLine($"Nessuna connessione {kind} su localhost: test saltato.");
            return;
        }
        var name = "navifox_selftest_" + Guid.NewGuid().ToString("N")[..8];
        var server = profile with { DefaultDatabase = provider.MaintenanceDatabase };
        await using (var admin = await provider.ConnectAsync(server, CancellationToken.None))
            await provider.ExecuteAsync(admin, provider.BuildCreateDatabaseSql(new DatabaseOptions(name)), 0, CancellationToken.None);
        try
        {
            await using var connection = await provider.ConnectAsync(profile with { DefaultDatabase = name }, CancellationToken.None);
            await test(provider, connection, kind == DatabaseKind.MySql ? name : "public");
        }
        finally
        {
            provider.ClearPools();
            await using var admin = await provider.ConnectAsync(server, CancellationToken.None);
            var drop = provider.BuildDropDatabaseSql(name) + (kind == DatabaseKind.PostgreSql ? " WITH (FORCE)" : string.Empty);
            await provider.ExecuteAsync(admin, drop, 0, CancellationToken.None);
        }
    }

    private static async Task RunAsync(IDialectProvider provider, DbConnection connection, params string[] statements)
    {
        foreach (var statement in statements) await provider.ExecuteAsync(connection, statement, 0, CancellationToken.None);
    }

    [Theory]
    [MemberData(nameof(Kinds))]
    public Task TableDesignRoundTrip(DatabaseKind kind) => WithTemporaryDatabaseAsync(kind, async (provider, connection, schema) =>
    {
        var mysql = kind == DatabaseKind.MySql;
        await RunAsync(provider, connection, mysql
            ? "CREATE TABLE t (id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(100) NOT NULL DEFAULT 'x', price DECIMAL(10,2), old INT, KEY ix_title (title))"
            : "CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(100) NOT NULL DEFAULT 'x', price NUMERIC(10,2), old INT); CREATE INDEX ix_title ON t (title)");
        var design = await provider.GetTableDesignAsync(connection, schema, schema, "t", CancellationToken.None);
        Assert.Empty(TableDesignSql.Build(mysql, schema, design, design));

        var columns = design.Columns.Where(c => c.Name != "old").Select(c => c.Name == "title" ? c with { Name = "headline", Length = 150 } : c).ToList();
        columns.Add(new DesignColumn(null, "code", "varchar", 20));
        var target = design with { Columns = columns, Indexes = design.Indexes.Select(i => i with { Columns = ["headline"] }).ToArray(), Comment = "prova" };
        foreach (var statement in TableDesignSql.Build(mysql, schema, design, target))
            await provider.ExecuteAsync(connection, statement, 0, CancellationToken.None);

        var after = await provider.GetTableDesignAsync(connection, schema, schema, "t", CancellationToken.None);
        Assert.Equal(["id", "headline", "price", "code"], after.Columns.Select(c => c.Name));
        Assert.Equal(150, after.Columns.Single(c => c.Name == "headline").Length);
        Assert.Equal("prova", after.Comment);
        Assert.Empty(TableDesignSql.Build(mysql, schema, after, after));
    });

    [Theory]
    [MemberData(nameof(Kinds))]
    public Task RoutineSaveAndRestore(DatabaseKind kind) => WithTemporaryDatabaseAsync(kind, async (provider, connection, schema) =>
    {
        var mysql = kind == DatabaseKind.MySql;
        var template = SchemaObjectSql.Template(mysql, schema, SchemaObjectKind.Routine);
        await RunAsync(provider, connection, template);
        var function = (await provider.ListSchemaObjectsAsync(connection, schema, schema, SchemaObjectKind.Routine, CancellationToken.None)).Single();
        var definition = await provider.GetSchemaObjectDefinitionAsync(connection, schema, schema, SchemaObjectKind.Routine, function, CancellationToken.None);
        Assert.Contains("nuova_funzione", definition);

        var plan = SchemaObjectSql.BuildSave(mysql, schema, SchemaObjectKind.Routine, function, definition, definition.Replace("* 2", "* 3"));
        foreach (var statement in plan.Statements) await provider.ExecuteAsync(connection, statement, 0, CancellationToken.None);
        var result = await provider.ExecuteAsync(connection, mysql ? "SELECT nuova_funzione(5)" : "SELECT public.nuova_funzione(5)", 1, CancellationToken.None);
        Assert.Equal("15", Convert.ToString(result.Rows[0][0]));
    });

    [Fact]
    public Task PostgresSequenceEdit() => WithTemporaryDatabaseAsync(DatabaseKind.PostgreSql, async (provider, connection, schema) =>
    {
        await RunAsync(provider, connection, SchemaObjectSql.SequenceSql(schema, null, new SequenceInfo("s", Start: 10, Increment: 5)).ToArray());
        var sequence = await provider.GetSequenceAsync(connection, schema, "s", CancellationToken.None);
        Assert.Equal(5, sequence.Increment);
        await RunAsync(provider, connection, SchemaObjectSql.SequenceSql(schema, sequence, sequence with { Increment = 2, Current = 100 }).ToArray());
        var after = await provider.GetSequenceAsync(connection, schema, "s", CancellationToken.None);
        Assert.Equal(2, after.Increment);
        Assert.Equal(100, after.Current);
    });
}
